const { existsSync, readdirSync, statSync } = require('node:fs')
const { join } = require('node:path')
const { readInstalledModules } = require('./module-manifest.cjs')

function collectPages(root, prefix, importPrefix) {
  if (!existsSync(root)) return []
  const pages = []
  const visit = (dir, parts) => {
    const entries = readdirSync(dir).sort()
    if (entries.includes('index.tsx')) {
      const suffix = parts.join('/')
      pages.push([suffix ? `${prefix}${suffix}` : `${prefix}index`, suffix ? `${importPrefix}/${suffix}` : importPrefix])
    }
    for (const entry of entries) {
      if (entry.startsWith('.') || entry === 'node_modules' || entry === '__tests__') continue
      const full = join(dir, entry)
      if (statSync(full).isDirectory()) visit(full, [...parts, entry])
    }
  }
  visit(root, [])
  return pages
}

function generateModuleComponents({ adminRoot, apiRoot, systemPages = {} }) {
  const installed = readInstalledModules(apiRoot)
  const pages = new Map(Object.entries(systemPages))
  for (const [key, specifier] of collectPages(join(adminRoot, 'src/pages'), './', '@/pages')) {
    if (pages.has(key)) throw new Error(`Duplicate Admin component key: ${key}`)
    pages.set(key, specifier)
  }
  for (const module of installed) {
    for (const [key, specifier] of collectPages(join(adminRoot, 'src/modules', module.id, 'pages'), `./modules/${module.id}/`, `@/modules/${module.id}/pages`)) {
      pages.set(key, specifier)
    }
  }
  return `// Generated by @yishan/core-admin/umi-plugin. Do not edit.\nimport type { ComponentType } from 'react'\n\nexport const moduleComponentsMap: Readonly<Record<string, () => Promise<{ default: ComponentType }>>> = Object.freeze({\n${[...pages].sort(([a], [b]) => a.localeCompare(b)).map(([key, specifier]) => `  ${JSON.stringify(key)}: () => import(${JSON.stringify(specifier)})`).join(',\n')}\n})\n`
}

module.exports = { generateModuleComponents }
