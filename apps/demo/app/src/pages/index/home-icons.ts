function normalizeIconKey(name?: string | null): string {
  return (name ?? '')
    .trim()
    .replace(/(Outlined|Filled|TwoTone)$/, '')
    .replace(/[-_\s]/g, '')
    .toLowerCase()
}

export function resolveHomeIcon(...candidates: (string | null | undefined)[]): HomeIconName {
  for (const candidate of candidates) {
    const alias = MENU_ICON_ALIASES[normalizeIconKey(candidate)]
    if (alias) return alias
  }
  return 'layoutGrid'
}

const cache = new Map<string, string>()

/** 生成可直接用于 style 的 background-image 值 */
export function homeIconBackground(name: HomeIconName, color: string, strokeWidth = 1.75): string {
  const key = `${name}|${color}|${strokeWidth}`
  const hit = cache.get(key)
  if (hit) return hit
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="${color}" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round">${LUCIDE_NODES[name]}</svg>`
  const value = `url("data:image/svg+xml,${encodeURIComponent(svg)}")`
  cache.set(key, value)
  return value
}
